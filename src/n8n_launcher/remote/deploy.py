def build_secrets_document(
    owner_email: str,
    owner_password: str,
    credentials: list[dict],
) -> dict:
    """Assemble the ``secrets.json`` upload payload for a publish."""
    return {
        "owner_email": owner_email,
        "owner_password": owner_password,
        "credentials": credentials,
    }
